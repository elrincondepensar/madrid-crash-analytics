"""Create a .gitignore for the Madrid road-safety project and sanity-check the repo.

What it does
1. Writes <root>/.gitignore (backs up any existing one when --force is used).
2. Creates data/raw/.gitkeep and data/processed/.gitkeep so the folders exist on clone.
3. If git is available and <root> is a repository, reports:
   - files already tracked that the new rules would ignore (need `git rm --cached`),
   - untracked, non-ignored files larger than --limit-mb (GitHub warns at 50 MB
     and rejects files over 100 MB).

Usage (from the project root, e.g. proyecto_madrid/):
    python scripts/50_phase11_make_gitignore.py
    python scripts/50_phase11_make_gitignore.py --force      # overwrite existing
    python scripts/50_phase11_make_gitignore.py --root "C:\\path\\to\\proyecto_madrid"
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

GITIGNORE = """\
# ============================================================
# madrid-road-safety  .gitignore  (generated by scripts/50_phase11_make_gitignore.py)
# ============================================================

# --- Data: regenerable from scripts/ and far too large for GitHub ---
data/raw/*
data/processed/*
data/interim/
!data/raw/.gitkeep
!data/processed/.gitkeep

# --- Caches and heavy intermediates ---
cache/

# --- Reports: version tables (json), markdown reports and final figures only ---
reports/figures/*
!reports/figures/final/

# --- Jupyter / Python ---
.ipynb_checkpoints/
__pycache__/
*.py[cod]
*.egg-info/
build/
dist/
.pytest_cache/
.ruff_cache/
.mypy_cache/
.coverage
htmlcov/

# --- Environments and secrets ---
.venv/
venv/
.env
*.env

# --- Editors and OS ---
.vscode/
.idea/
.DS_Store
Thumbs.db
desktop.ini
~$*

# --- Backups created by the .gitignore generator ---
.gitignore.bak-*
"""

PLACEHOLDERS = ["data/raw/.gitkeep", "data/processed/.gitkeep"]


def run_git(root: Path, *args: str) -> list[str] | None:
    """Run a git command in `root`; return stdout lines or None if it fails."""
    try:
        res = subprocess.run(
            ["git", "-c", "core.quotepath=false", "-C", str(root), *args],
            capture_output=True, text=True, encoding="utf-8",
        )
    except FileNotFoundError:
        return None
    return res.stdout.splitlines() if res.returncode == 0 else None


def write_gitignore(root: Path, force: bool) -> bool:
    target = root / ".gitignore"
    if target.exists():
        if not force:
            print(f"[!] {target} already exists. Re-run with --force to replace it "
                  "(a timestamped backup is kept).")
            return False
        backup = root / f".gitignore.bak-{datetime.now():%Y%m%d-%H%M%S}"
        shutil.copy2(target, backup)
        print(f"[i] Backup saved: {backup.name}")
    target.write_text(GITIGNORE, encoding="utf-8", newline="\n")
    print(f"[ok] Wrote {target}")
    return True


def create_placeholders(root: Path) -> None:
    for rel in PLACEHOLDERS:
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.touch(exist_ok=True)
    print("[ok] Placeholders: " + ", ".join(PLACEHOLDERS))


def check_repo(root: Path, limit_mb: float) -> None:
    if run_git(root, "rev-parse", "--is-inside-work-tree") is None:
        print("[i] Not a git repository (or git not installed): skipping repo checks. "
              "Run `git init` and re-run this script to get them.")
        return

    tracked_ignored = run_git(root, "ls-files", "-c", "-i", "--exclude-standard") or []
    if tracked_ignored:
        print(f"\n[!] {len(tracked_ignored)} tracked file(s) now match the ignore rules. "
              "They stay in the repo until you untrack them:")
        for f in tracked_ignored[:15]:
            print("      " + f)
        if len(tracked_ignored) > 15:
            print(f"      ... and {len(tracked_ignored) - 15} more")
        print("    Untrack (keeps files on disk), then commit:")
        print("      git rm -r --cached .")
        print("      git add .")
        print("      git commit -m \"Apply .gitignore\"")
        print("    Note: this does NOT remove them from past commits (history stays large).")
    else:
        print("[ok] No tracked file conflicts with the ignore rules.")

    untracked = run_git(root, "ls-files", "-o", "--exclude-standard") or []
    big = []
    for rel in untracked:
        p = root / rel
        try:
            size_mb = p.stat().st_size / 1e6
        except OSError:
            continue
        if size_mb >= limit_mb:
            big.append((size_mb, rel))
    if big:
        print(f"\n[!] Untracked, non-ignored files >= {limit_mb:g} MB (GitHub limits):")
        for size_mb, rel in sorted(big, reverse=True):
            print(f"      {size_mb:8.1f} MB  {rel}")
    else:
        print(f"[ok] No untracked, non-ignored file >= {limit_mb:g} MB.")

    total = sum((root / r).stat().st_size for r in untracked if (root / r).exists())
    print(f"[i] Untracked files that would be added: {len(untracked)} "
          f"({total / 1e6:.1f} MB total)")


def main() -> int:
    default_root = Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--root", type=Path, default=default_root, help="project root (default: parent of scripts/)")
    ap.add_argument("--force", action="store_true", help="overwrite an existing .gitignore (backup kept)")
    ap.add_argument("--limit-mb", type=float, default=50.0, help="size threshold for the large-file check")
    args = ap.parse_args()

    root = args.root.resolve()
    if not root.is_dir():
        print(f"[x] Root not found: {root}")
        return 2
    print(f"Project root: {root}")

    if not write_gitignore(root, args.force):
        return 1
    create_placeholders(root)
    check_repo(root, args.limit_mb)
    return 0


if __name__ == "__main__":
    sys.exit(main())